"""Tuning: sweep results -> best recipe per (backbone, init) on val -> tuned grid YAML (rules).

`python -m bakeoff.tune configs/sweep.yaml configs/grid.yaml` -> <sweep out_dir>/tuned.yaml
then `python -m bakeoff.grid <that tuned.yaml>` (same runs as grid.yaml, + per-pair rules).
"""
import argparse
import os

import yaml

from .grid import expand
from .results import KEY, read_results


def pick(sweep_path, overrides=()):
    """{(backbone, init): {swept key: best value}} by top1_val (never test). Only rows w/ a sweep run hash."""
    return _pick(expand(sweep_path, overrides), _swept_keys(sweep_path))


def _swept_keys(sweep_path):
    with open(sweep_path) as file:
        return [key for key in yaml.safe_load(file)["grid"] if key not in KEY]


def _pick(runs, swept_keys):
    val_score = {}  # config_hash -> mean top1_val
    for results_csv in {run.cfg.results_csv for run in runs}:
        results = read_results(results_csv)
        if results is not None:
            val_score.update(results.groupby("config_hash").top1_val.mean().dropna().to_dict())
    best = {}  # (backbone, init) -> (score, swept values)
    for run in runs:  # grid order -> first wins ties
        pair, score = (run.cfg.backbone, run.cfg.init), val_score.get(run.run_id)
        if score is not None and (pair not in best or score > best[pair][0]):
            best[pair] = (score, {key: getattr(run.cfg, key) for key in swept_keys})
    return {pair: hparams for pair, (_, hparams) in best.items()}


def write_tuned(sweep_path, grid_path, out=None, overrides=()):
    """grid.yaml + rules {when: pair, set: pick} -> out (default <sweep out_dir>/tuned.yaml). -> (out, picks)."""
    runs = expand(sweep_path, overrides)
    picks = _pick(runs, _swept_keys(sweep_path))
    if missing := sorted({(run.cfg.backbone, run.cfg.init) for run in runs} - set(picks)):
        print("no sweep results (fixed recipe kept):", missing)
    with open(grid_path) as file:
        spec = yaml.safe_load(file)
    spec["base"] = os.path.join(os.path.dirname(os.path.abspath(grid_path)), spec.get("base", "default.yaml"))
    spec["rules"] = (spec.get("rules") or []) + [  # appended -> tuned wins over grid's own rules
        {"when": dict(backbone=backbone, init=init), "set": hparams}
        for (backbone, init), hparams in sorted(picks.items())]
    out = out or os.path.join(runs[0].cfg.out_dir, "tuned.yaml")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w") as file:
        file.write(f"# generated by bakeoff.tune from {os.path.basename(sweep_path)} (best top1_val per pair)\n")
        yaml.safe_dump(spec, file, sort_keys=False)
    return out, picks


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("sweep")
    parser.add_argument("grid")
    parser.add_argument("--out")
    parser.add_argument("--set", nargs="*", default=[], metavar="KEY=VAL",
                        help="same overrides as the sweep launch")
    args = parser.parse_args(argv)
    out, picks = write_tuned(args.sweep, args.grid, args.out, args.set)
    for pair, hparams in sorted(picks.items()):
        print(*pair, hparams)
    print("->", out)
    return out


if __name__ == "__main__":
    main()
