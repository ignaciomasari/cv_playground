"""Tuning: sweep results -> best recipe per (backbone, init) on val -> tuned grid YAML (rules).

`python -m bakeoff.tune configs/sweep.yaml configs/grid.yaml` -> <sweep out_dir>/tuned.yaml
then `python -m bakeoff.grid <that tuned.yaml>` (same runs as grid.yaml, + per-pair rules).
"""
import argparse
import os

import yaml

from .grid import expand
from .results import KEY, read_results


def pick(sweep_path, overrides=()):
    """{(backbone, init): {swept key: best value}} by top1_val (never test). Only rows w/ a sweep run hash."""
    return _pick(expand(sweep_path, overrides), _swept_keys(sweep_path))


def _swept_keys(sweep_path):
    with open(sweep_path) as f:
        return [k for k in yaml.safe_load(f)["grid"] if k not in KEY]


def _pick(runs, keys):
    score = {}
    for csv in {r.cfg.results_csv for r in runs}:
        df = read_results(csv)
        if df is not None:
            score.update(df.groupby("config_hash").top1_val.mean().dropna().to_dict())
    best = {}
    for r in runs:  # grid order -> first wins ties
        pair, s = (r.cfg.backbone, r.cfg.init), score.get(r.run_id)
        if s is not None and (pair not in best or s > best[pair][0]):
            best[pair] = (s, {k: getattr(r.cfg, k) for k in keys})
    return {pair: hp for pair, (_, hp) in best.items()}


def write_tuned(sweep_path, grid_path, out=None, overrides=()):
    """grid.yaml + rules {when: pair, set: pick} -> out (default <sweep out_dir>/tuned.yaml). -> (out, picks)."""
    runs = expand(sweep_path, overrides)
    picks = _pick(runs, _swept_keys(sweep_path))
    if missing := sorted({(r.cfg.backbone, r.cfg.init) for r in runs} - set(picks)):
        print("no sweep results (fixed recipe kept):", missing)
    with open(grid_path) as f:
        spec = yaml.safe_load(f)
    spec["base"] = os.path.join(os.path.dirname(os.path.abspath(grid_path)), spec.get("base", "default.yaml"))
    spec["rules"] = (spec.get("rules") or []) + [  # appended -> tuned wins over grid's own rules
        {"when": dict(backbone=bb, init=init), "set": hp} for (bb, init), hp in sorted(picks.items())]
    out = out or os.path.join(runs[0].cfg.out_dir, "tuned.yaml")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w") as f:
        f.write(f"# generated by bakeoff.tune from {os.path.basename(sweep_path)} (best top1_val per pair)\n")
        yaml.safe_dump(spec, f, sort_keys=False)
    return out, picks


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("sweep")
    p.add_argument("grid")
    p.add_argument("--out")
    p.add_argument("--set", nargs="*", default=[], metavar="KEY=VAL", help="same overrides as the sweep launch")
    a = p.parse_args(argv)
    out, picks = write_tuned(a.sweep, a.grid, a.out, a.set)
    for pair, hp in sorted(picks.items()):
        print(*pair, hp)
    print("->", out)
    return out


if __name__ == "__main__":
    main()
