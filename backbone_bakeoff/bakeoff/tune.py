"""Tuning: sweep results -> best recipe per (backbone, init) on val -> tuned grid YAML (rules).

`python -m bakeoff.tune configs/sweep.yaml configs/grid.yaml` -> <sweep out_dir>/tuned.yaml
then `python -m bakeoff.grid <that tuned.yaml>` (same runs as grid.yaml, + per-pair rules).
"""
import argparse
import logging
import os
from collections.abc import Sequence
from typing import Any

from . import setup_logging
from .grid import GridSpec, Rule, Run, plain
from .results import read_results

Pair = tuple[str, str]  # (backbone, init)
log = logging.getLogger("bakeoff.tune")  # not __name__: "__main__" under `python -m`


def pick(sweep_path: str, overrides: Sequence[str] = ()) -> dict[Pair, dict[str, Any]]:
    """{(backbone, init): {swept key: best value}} by top1_val (never test). Only rows w/ a sweep run hash."""
    sweep = GridSpec.load(sweep_path)
    return _pick(sweep.expand(overrides), sweep.swept_keys)


def _pick(runs: Sequence[Run], swept_keys: Sequence[str]) -> dict[Pair, dict[str, Any]]:
    val_score = {}  # config_hash -> mean top1_val
    for results_csv in {run.cfg.results_csv for run in runs}:
        results = read_results(results_csv)
        if results is not None:
            val_score.update(results.groupby("config_hash").top1_val.mean().dropna().to_dict())
    best = {}  # (backbone, init) -> (score, swept values)
    for run in runs:  # grid order -> first wins ties
        pair, score = (run.cfg.backbone, str(run.cfg.init)), val_score.get(run.run_id)
        if score is not None and (pair not in best or score > best[pair][0]):
            best[pair] = (score, {key: plain(getattr(run.cfg, key)) for key in swept_keys})
    return {pair: hparams for pair, (_, hparams) in best.items()}


def write_tuned(sweep_path: str, grid_path: str, out: str | None = None,
                overrides: Sequence[str] = ()) -> tuple[str, dict[Pair, dict[str, Any]]]:
    """grid.yaml + rules {when: pair, set: pick} -> out (default <sweep out_dir>/tuned.yaml). -> (out, picks)."""
    sweep = GridSpec.load(sweep_path)
    runs = sweep.expand(overrides)
    picks = _pick(runs, sweep.swept_keys)
    if missing := sorted({(run.cfg.backbone, str(run.cfg.init)) for run in runs} - set(picks)):
        log.warning("no sweep results (fixed recipe kept): %s", missing)
    tuned = GridSpec.load(grid_path).with_rules(  # appended -> tuned wins over grid's own rules
        [Rule(dict(backbone=backbone, init=init), hparams) for (backbone, init), hparams in sorted(picks.items())])
    out = out or os.path.join(runs[0].cfg.out_dir, "tuned.yaml")
    tuned.dump(out, header=f"# generated by bakeoff.tune from {os.path.basename(sweep_path)} (best top1_val per pair)\n")
    return out, picks


def main(argv: Sequence[str] | None = None) -> str:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("sweep")
    parser.add_argument("grid")
    parser.add_argument("--out")
    parser.add_argument("--set", nargs="*", default=[], metavar="KEY=VAL",
                        help="same overrides as the sweep launch")
    args = parser.parse_args(argv)
    setup_logging()
    out, picks = write_tuned(args.sweep, args.grid, args.out, args.set)
    for pair, hparams in sorted(picks.items()):
        print(*pair, hparams)
    print("->", out)
    return out


if __name__ == "__main__":
    main()
